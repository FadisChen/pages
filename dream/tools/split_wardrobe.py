"""Split four generated 5-column/4-age atlases into game-ready WebP assets.
Usage: python dream/tools/split_wardrobe.py atlas1.png atlas2.png atlas3.png atlas4.png
Pillow, numpy and scipy are required. This only crops, pads and rescales existing generated art.
"""
from pathlib import Path
import argparse
import json
from PIL import Image
import numpy as np
from scipy import ndimage

GROUPS = [
 ['daily','academy','travel','swim','gala'],
 ['demon','maid','knight','mage','chef'],
 ['healer','ranger','farmer','sailor','artist'],
 ['scholar','dancer','winter','summer','festival'],
]

def main():
 parser=argparse.ArgumentParser(description=__doc__)
 parser.add_argument('atlases',nargs=4,type=Path)
 args=parser.parse_args()
 root=Path(__file__).resolve().parents[1]
 out=root/'assets'/'outfits';out.mkdir(parents=True,exist_ok=True)
 manifest=[]
 for source,names in zip(args.atlases,GROUPS):
  atlas=Image.open(source).convert('RGBA');w,h=atlas.size
  alpha=atlas.getchannel('A')
  projection=[sum(v>64 for v in alpha.crop((0,y,w,y+1)).tobytes()) for y in range(h)]
  boundaries=[0]
  for row in range(1,4):
   middle=round(h*row/4);radius=round(h*.065)
   candidates=range(max(boundaries[-1]+1,middle-radius),min(h-1,middle+radius))
   best=min(candidates,key=lambda y:(projection[y],abs(y-middle)))
   boundaries.append(best)
  boundaries.append(h)
  for col,name in enumerate(names):
   for age in range(4):
    rect=(round(w*col/5),boundaries[age],round(w*(col+1)/5),boundaries[age+1])
    sprite=atlas.crop(rect)
    # Isolate this character from disconnected neighboring hems or capes.
    pixels=np.array(sprite)
    labels,count=ndimage.label(pixels[:,:,3]>48)
    if not count:raise ValueError(f'No character: {name}/{age}')
    sizes=np.bincount(labels.ravel());sizes[0]=0
    main=labels==sizes.argmax()
    mask=ndimage.binary_dilation(main,iterations=2)
    pixels[:,:,3]=np.where(mask,pixels[:,:,3],0)
    sprite=Image.fromarray(pixels)
    bbox=sprite.getchannel('A').point(lambda a:255 if a>32 else 0).getbbox()
    if not bbox:raise ValueError(f'Empty cell: {name}/{age}')
    sprite=sprite.crop(bbox)
    max_height=[360,384,408,420][age]
    scale=min(230/sprite.width,max_height/sprite.height)
    sprite=sprite.resize((round(sprite.width*scale),round(sprite.height*scale)),Image.Resampling.LANCZOS)
    tile=Image.new('RGBA',(256,448))
    tile.alpha_composite(sprite,((256-sprite.width)//2,432-sprite.height))
    dest=out/f'{name}-{age}.webp';tile.save(dest,'WEBP',quality=92,method=4)
    manifest.append({'outfit':name,'stage':age,'path':dest.relative_to(root).as_posix(),'source':source.name,'crop':list(rect),'size':[256,448]})
 css=['/* Generated by tools/split_wardrobe.py; one transparent asset per outfit/age. */']
 for item in manifest:
  css.append(f'.sprite.outfit-{item["outfit"]}.stage-{item["stage"]}{{background-image:url("outfits/{item["outfit"]}-{item["stage"]}.webp");background-position:center bottom;background-size:contain}}')
 (root/'assets'/'wardrobe.css').write_text('\n'.join(css)+'\n')
 (root/'assets'/'wardrobe-manifest.json').write_text(json.dumps(manifest,ensure_ascii=False,indent=2)+'\n')
 print(f'Created {len(manifest)} sprites in {out}')

if __name__=='__main__':main()
