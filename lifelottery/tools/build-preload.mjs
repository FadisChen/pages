// Keeps the <link rel="modulepreload"> list in index.html in step with the module graph (PLAN Phase 5E, "load speed").
//
//   node tools/build-preload.mjs            rewrite the block between the marker comments in index.html
//   node tools/build-preload.mjs --check    exit 1 (and say why) when the block is stale; writes nothing
//
// Without a hint the browser finds modules one import level at a time (main.js, then what main.js imports, then what those import ...),
// a waterfall of round trips. Listing every module up front lets all of them download in parallel.
//
// The list is every module reachable from js/main.js through static `import ... from`, `export ... from` and `import('...')`
// (the router's template import of ui/screens/${name}.js stands for every file in that folder). Two groups:
//   - first-paint modules: the static closure of js/main.js and of the landing screen. These are preloaded at normal priority.
//   - lazy modules: everything else (the engine and all event texts, the other screens, map zoom ...). They are listed too, but inside an
//     inert <template>: preloading them at load would compete with the landing screen for bandwidth (measured: first paint 3x slower
//     on a slow connection). The game copies them into <head> when the page is idle or the player reaches for "start".
// The block sits at the end of <body> (modulepreload is allowed there), right before the module script: measured on a throttled
// connection, that keeps the stylesheet ahead of the preloads, so the page paints about 10% sooner than with the links in <head>.
// Nothing outside lifelottery/ is ever listed (PLAN 2.1) and js/theme-init.js is a classic script, not a module.

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

export const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const ENTRY = 'js/main.js';
export const FIRST_PAINT_ENTRIES = [ENTRY, 'js/ui/screens/landing.js'];
export const START = '<!-- preload:start (generated by tools/build-preload.mjs; do not edit by hand) -->';
export const END = '<!-- preload:end -->';

const posix = (p) => p.split(path.sep).join('/');

/** Import specifiers of a module: { static: [...], dynamic: [...] } (dynamic template imports end in a '/' folder marker). */
export function importsOf(source) {
  // comments: whole-line `//` comments and block comments that start a line (a `/*` inside a line comment, as in "screens/*.js", is text)
  const code = source.replace(/^[ \t]*\/\/[^\n]*$/gm, '').replace(/^[ \t]*\/\*[\s\S]*?\*\//gm, '');
  const stat = new Set(), dyn = new Set();
  for (const m of code.matchAll(/(?:^|[;\s}])(?:import|export)\s+(?:[^'"`;()]*?\s+from\s+)?['"]([^'"]+)['"]/g)) stat.add(m[1]);
  for (const m of code.matchAll(/\bimport\(\s*(['"`])([^'"`]*)\1\s*\)/g)) {
    if (!m[2].includes('${')) dyn.add(m[2]);
  }
  for (const m of code.matchAll(/\bimport\(\s*`([^`]*\$\{[^`]*)`\s*\)/g)) dyn.add(m[1].slice(0, m[1].indexOf('${')).replace(/[^/]*$/, '') + '*'); // folder wildcard
  return { static: [...stat], dynamic: [...dyn] };
}

/** Resolve a relative specifier from a module (both as paths relative to ROOT). Non-relative specifiers are ignored. */
function resolveSpec(from, spec) {
  if (!spec.startsWith('.')) return null;
  return posix(path.normalize(path.join(path.dirname(from), spec)));
}

/**
 * Walk the module graph. Returns { all: [paths], firstPaint: [paths], lazy: [paths] } relative to lifelottery/, in a stable order
 * (first-paint modules in discovery order from main.js, lazy ones alphabetically).
 */
export function computePreload(root = ROOT) {
  const info = new Map(); // path -> { static: [paths], dynamic: [paths] }
  const read = (rel) => {
    if (info.has(rel)) return info.get(rel);
    const abs = path.join(root, rel);
    if (!fs.existsSync(abs)) throw new Error(`module not found: ${rel}`);
    const { static: st, dynamic } = importsOf(fs.readFileSync(abs, 'utf8'));
    const entry = { static: [], dynamic: [] };
    info.set(rel, entry);
    for (const spec of st) { const r = resolveSpec(rel, spec); if (r) entry.static.push(r); }
    for (const spec of dynamic) {
      const r = resolveSpec(rel, spec.endsWith('*') ? `${spec}x.js` : spec);
      if (!r) continue;
      if (spec.endsWith('*')) {
        const dir = path.dirname(r);
        for (const f of fs.readdirSync(path.join(root, dir)).sort()) if (f.endsWith('.js')) entry.dynamic.push(posix(path.join(dir, f)));
      } else entry.dynamic.push(r);
    }
    return entry;
  };

  const closure = (entries, withDynamic) => {
    const seen = new Set(), order = [];
    const queue = [...entries];
    while (queue.length) {
      const p = queue.shift();
      if (seen.has(p)) continue;
      seen.add(p);
      order.push(p);
      const e = read(p);
      queue.push(...e.static, ...(withDynamic ? e.dynamic : []));
    }
    return order;
  };

  const all = closure([ENTRY], true);
  const firstPaint = closure(FIRST_PAINT_ENTRIES, false);
  const fp = new Set(firstPaint);
  const lazy = all.filter((p) => !fp.has(p)).sort();
  return { all: [...firstPaint, ...lazy], firstPaint, lazy };
}

export const LATER_ID = 'preload-later';

/**
 * The text between the markers: the first-paint links, then the lazy ones inside <template id="preload-later">. A <template> is
 * inert, so the lazy links cost nothing at load; ui/session.js warm() copies them into <head> once the page is idle (or the
 * player reaches for "start"), which makes the browser fetch the whole engine in parallel instead of one import level at a time.
 */
export function renderBlock({ firstPaint, lazy }) {
  return [
    ...firstPaint.map((p) => `  <link rel="modulepreload" href="${p}">`),
    `  <template id="${LATER_ID}">`,
    ...lazy.map((p) => `    <link rel="modulepreload" href="${p}" fetchpriority="low">`),
    '  </template>',
  ].join('\n');
}

/** index.html with the block replaced. Throws when the markers are missing. */
export function withBlock(html, graph) {
  const a = html.indexOf(START), b = html.indexOf(END);
  if (a < 0 || b < a) throw new Error('index.html has no preload markers');
  return `${html.slice(0, a + START.length)}\n${renderBlock(graph)}\n  ${html.slice(b)}`;
}

/** The modulepreload entries currently in index.html: [{ href, later }] in document order (`later`: inside the lazy template). */
export function currentBlock(html) {
  const a = html.indexOf(START), b = html.indexOf(END);
  if (a < 0 || b < a) return null;
  const block = html.slice(a, b);
  const t0 = block.indexOf(`<template id="${LATER_ID}">`);
  return [...block.matchAll(/<link rel="modulepreload" href="([^"]+)"[^>]*>/g)].map((m) => ({ href: m[1], later: t0 >= 0 && m.index > t0 }));
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const file = path.join(ROOT, 'index.html');
  const html = fs.readFileSync(file, 'utf8');
  const graph = computePreload();
  const next = withBlock(html, graph);
  if (process.argv.includes('--check')) {
    if (next !== html) { console.error('index.html modulepreload list is stale: run  node tools/build-preload.mjs'); process.exit(1); }
    console.log(`modulepreload list is current (${graph.all.length} modules, ${graph.firstPaint.length} for the first paint)`);
  } else {
    fs.writeFileSync(file, next);
    console.log(`index.html: ${graph.all.length} modulepreload links (${graph.firstPaint.length} first-paint, ${graph.lazy.length} lazy)`);
  }
}
