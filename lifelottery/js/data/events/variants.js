// Alternative phrasings (Phase 5C) for the ~65 ordinary events that turn up most often, so the second life of a player
// who meets "流感季" or "返鄉過節" again reads a different scene.
//
//   { eventId: [ variant, variant, ... ] }      variant = string | (s, h) => string
//
// index.js attaches each list to its event as `ev.variants`; the event's own `text` stays variant 0. The engine
// (events.js, renderText) picks (hash(seed, id) + number of earlier lives that met the event) mod (1 + variants.length),
// so a given life is stable and the next one moves on to the next phrasing.
//
// Rules for a variant (they are checked by tests/novelty.test.mjs and the coherence audit):
//   * same situation, same meaning and the same state constraints as the event: it may not mention a partner, a child, a
//     job, school, a phone, ... unless the event's own text may; effects, choices and follow-ups stay as they are;
//   * no random numbers (h.rand / h.pick / h.chance) and no state changes: a variant must not change which events fire;
//   * second person, Traditional Chinese (Taiwan usage), concrete and humane, 60-160 characters.
// Major events (with choices) keep the open question their options answer.
//
// Helpers: two(h, low, high) = h.byIncome({ L: low, UM: high }) (LM falls back to low, H to high).

